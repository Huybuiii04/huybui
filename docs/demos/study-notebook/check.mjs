import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { chromium } from 'playwright'
import AxeBuilder from '@axe-core/playwright'

const base = process.env.DEMO_URL || 'http://127.0.0.1:5176/'
const output = new URL('../../../test-results/notebook-demo/', import.meta.url)
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const go = async view => {
  await page.goto(`${base}#${view}`)
  await page.locator(view === 'practice' ? '#practice' : `[data-view="${view}"]`).waitFor()
  await page.evaluate(() => document.fonts.ready)
}
const screenshot = async name => page.screenshot({ path: new URL(`${name}.png`, output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true })
try {
  await go('overview')
  await page.getByRole('button', { name: 'Thu gọn sidebar' }).click()
  await page.waitForFunction(() => Math.round(document.querySelector('.sidebar').getBoundingClientRect().width) === 78)
  assert.equal(await page.getByRole('button', { name: 'Mở rộng sidebar' }).getAttribute('aria-expanded'), 'false')
  await page.getByRole('button', { name: 'Mở rộng sidebar' }).click()
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: width === 1440 ? 1000 : width === 768 ? 1024 : 844 })
    for (const view of ['overview', 'reading', 'writing', 'my-writing', 'vocabulary']) {
      await go(view)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${view} overflow at ${width}`)
      if (['overview', 'reading', 'writing'].includes(view)) await screenshot(`${view}-${width}`)
    }
  }
  await go('reading')
  await page.getByRole('button', { name: 'Xóa lọc', exact: true }).click()
  assert.match(await page.locator('#reading-count').innerText(), /^52 đề/)
  assert.equal(await page.locator('.test-card').count(), 12)
  await page.getByRole('button', { name: 'Tiếp', exact: true }).click()
  assert.match(await page.locator('#pagination').innerText(), /Trang 2 \/ 5/)
  await page.locator('#reading-search').fill('Cambridge 21 test 4')
  assert.equal(await page.locator('.test-card').count(), 1)
  await page.locator('#test-filter').selectOption('3')
  assert.equal(await page.locator('.test-card').count(), 0)
  await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).click()
  await page.locator('#book-filter').selectOption('21')
  await page.locator('#reading-search').fill('Cam21-Test4')
  await page.getByRole('button', { name: 'Thử giao diện', exact: true }).click()
  await page.locator('#practice').waitFor()
  assert.equal(await page.locator('#app-shell').isVisible(), false)
  await page.getByRole('button', { name: 'Câu hỏi', exact: true }).click()
  assert.equal(await page.locator('#passage-pane').isVisible(), false)
  await page.locator('input[name=q1][value=TRUE]').check()
  await page.locator('input[name=q2][value=FALSE]').check()
  await page.locator('input[name=q3][value="NOT GIVEN"]').check()
  await page.locator('input[name=q4]').fill(' 2021 ')
  await page.locator('input[name=q5]').fill('saturday')
  await page.locator('input[name=q6]').fill('VOLUNTEERS')
  assert.equal(await page.locator('#reading-progress').innerText(), '6 / 6 câu')
  await page.getByRole('button', { name: 'Bài đọc', exact: true }).click()
  assert.equal(await page.locator('.questions-pane').isVisible(), false)
  await page.getByRole('button', { name: 'Câu hỏi', exact: true }).click()
  assert.equal(await page.locator('input[name=q4]').inputValue(), ' 2021 ')
  await page.getByRole('button', { name: 'Nộp bài mẫu', exact: true }).click()
  assert.equal(await page.locator('#score-label').innerText(), '6 / 6 câu đúng')
  assert.equal(await page.locator('.question.correct').count(), 6)
  await page.locator('#question-1 summary').click()
  assert.equal(await page.locator('#question-1 details').getAttribute('open'), '')
  await screenshot('reading-result-390')
  const roomAxe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  assert.deepEqual(roomAxe.violations.map(item => ({ id: item.id, nodes: item.nodes.map(node => node.target) })), [], 'Reading accessibility')
  await page.getByRole('button', { name: 'Làm lại bài mẫu', exact: true }).click()
  assert.equal(await page.locator('#reading-progress').innerText(), '0 / 6 câu')
  await page.getByRole('button', { name: 'Trở về kho Reading' }).click()
  assert.equal(await page.locator('#reading-search').inputValue(), 'Cam21-Test4')
  await go('writing')
  const title = 'Một ý tưởng <riêng>'
  await page.locator('#writing-title').fill(title)
  await page.locator('#writing-body').fill('Small steps help us build a useful habit.')
  assert.equal(await page.locator('#word-count').innerText(), '8 từ')
  await page.getByRole('link', { name: 'Xem bản nháp', exact: true }).click()
  assert.equal(await page.locator('#draft-list strong').innerText(), title)
  assert.equal(await page.locator('#draft-list img').count(), 0)
  await page.locator('#draft-list a').click()
  assert.equal(await page.locator('#writing-body').inputValue(), 'Small steps help us build a useful habit.')
  await page.getByRole('button', { name: 'Xem gợi ý demo', exact: true }).click()
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#feedback-dialog').isVisible(), false)
  await go('overview')
  await page.getByRole('button', { name: 'Mở menu', exact: true }).click()
  await page.locator('#mobile-drawer').waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#mobile-drawer').isVisible(), false)
  assert.equal(await page.evaluate(() => document.activeElement.id), 'open-menu')
  await go('vocabulary')
  await page.getByRole('button', { name: 'Lật thẻ', exact: true }).click()
  assert.match(await page.locator('#flashcard-meaning').innerText(), /một bước nhỏ/)
  await page.getByRole('button', { name: 'Từ tiếp theo', exact: true }).click()
  assert.equal(await page.locator('#flashcard-word').innerText(), 'make progress')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await go('overview')
  for (const theme of ['light', 'dark']) {
    await page.evaluate(value => document.documentElement.dataset.theme = value, theme)
    const a11y = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    assert.deepEqual(a11y.violations.map(item => ({ id: item.id, nodes: item.nodes.map(node => node.target) })), [], `${theme} accessibility`)
    await screenshot(`overview-${theme}-1440`)
  }
  await go('practice')
  const bounds = await page.evaluate(() => [...document.querySelectorAll('.reading-pane')].map(el => { const r=el.getBoundingClientRect(); return { x:r.x,y:r.y,right:r.right,bottom:r.bottom } }))
  assert.ok(bounds[0].right <= bounds[1].x, 'Desktop Reading panes overlap')
  assert.ok(bounds.every(item => item.bottom <= 1000), 'Reading exceeds viewport')
  await screenshot('reading-room-dark-1440')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await go('overview')
  assert.equal(await page.evaluate(() => document.getAnimations().length), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: filters, pagination, sidebar/menu, mobile Reading, 6/6 grading, explanations, drafts, flashcards, 3 sizes, light/dark accessibility, reduced motion; no page errors.')
} catch (error) {
  await screenshot('check-failure')
  throw error
} finally { await browser.close() }
