import { chromium } from 'playwright'
const base = process.env.TEST_URL ?? 'http://127.0.0.1:5173'
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } })
const page = await context.newPage()
await page.goto(`${base}/auth`)
await page.getByLabel('Email').fill(process.env.ADMIN_EMAIL ?? 'admin@gmail.com')
await page.getByLabel(/^Mật khẩu|Password/).fill(process.env.ADMIN_PASSWORD ?? 'admin123')
await page.getByRole('button', { name: /Đăng nhập|Sign in/ }).click()
await page.waitForURL(u => !u.pathname.startsWith('/auth'), { timeout: 30000 })
await page.goto(`${base}/admin`)
await page.getByLabel(/Mật khẩu quản trị|Admin password/).fill(process.env.ADMIN_PASSWORD ?? 'admin123')
await page.getByRole('button', { name: /Mở bảng quản trị|Unlock/ }).click()
await page.locator('.admin-stats .stat-card').first().waitFor({ timeout: 30000 })
await page.waitForTimeout(2000)
await page.screenshot({ path: 'test-results/admin-dashboard.png', fullPage: false })
await page.getByRole('button', { name: /Người dùng|Users/, exact: true }).click()
await page.locator('.usage-table .usage-row').first().waitFor({ timeout: 30000 })
await page.locator('.usage-table .text-link').first().click()
await page.getByText(/Đề còn lại|Prompts not written yet/).first().waitFor({ timeout: 30000 })
await page.waitForTimeout(1500)
await page.screenshot({ path: 'test-results/admin-user-detail.png', fullPage: false })
console.log('da chup 2 anh')
await browser.close()
